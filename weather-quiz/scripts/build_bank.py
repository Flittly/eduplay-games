def build_options(q):
    """由题目 id 的 md5 作种子：干扰项从候选池里取 3 个同族项，答案落位由哈希决定。
    这样选项分布均匀（不会出现答案老在第 1 个位置），且每次构建结果完全可复现。"""
    h = hashlib.md5(q["id"].encode("utf-8")).hexdigest()
    rnd = random.Random(h)
    others = [x for x in q["pool"] if x != q["answer"]]
    rnd.shuffle(others)
    opts = others[:3]
    opts.insert(int(h[:8], 16) % 4, q["answer"])
    return opts


def check():
    errs = []
    ids = [q["id"] for q in Q]
    if len(ids) != len(set(ids)):
        errs.append("题目 id 有重复")
    for q in Q:
        if len(q["pool"]) < 4:
            errs.append("%s：候选池不足 4 项" % q["id"])
        if q["answer"] not in q["pool"]:
            errs.append("%s：答案不在候选池中" % q["id"])
        if len(set(q["pool"])) != len(q["pool"]):
            errs.append("%s：候选池有重复项" % q["id"])
        if len(q["options"]) != 4 or len(set(q["options"])) != 4:
            errs.append("%s：选项不是 4 个互不相同的项" % q["id"])
        if q["answer"] not in q["options"]:
            errs.append("%s：选项中缺少正确答案" % q["id"])
        if not q["hints"] or any(not h.strip() for h in q["hints"]):
            errs.append("%s：提示为空" % q["id"])
        if not q["explain"].strip() or not q["prompt"].strip():
            errs.append("%s：题干或解析为空" % q["id"])
    # 等级数量
    for lv in ("junior", "senior"):
        n = sum(1 for q in Q if q["level"] == lv)
        print("  %s 题数：%d" % (lv, n))
    # 答案位置分布（防止答案总在同一个位置）
    dist = {}
    for q in Q:
        dist[q["options"].index(q["answer"])] = dist.get(
            q["options"].index(q["answer"]), 0) + 1
    print("  答案位置分布（0-3）：", dict(sorted(dist.items())))
    # 图片存在性
    for q in Q:
        p = os.path.join(ROOT, "public", q["image"])
        if not os.path.exists(p):
            errs.append("%s：缺图片 %s" % (q["id"], q["image"]))
    for eid, _n, _c, _l, _s in E:
        found = any(os.path.exists(os.path.join(ASSETS, eid + ext))
                    for ext in (".svg", ".jpg"))
        if not found:
            errs.append("图鉴条目缺素材：%s" % eid)
    # 分类覆盖
    cats = {}
    for q in Q:
        cats[(q["level"], q["category"])] = cats.get((q["level"], q["category"]), 0) + 1
    for k in sorted(cats):
        print("  %s · %s：%d 题" % (k[0], k[1], cats[k]))
    return errs


def main():
    for q in Q:
        q["options"] = build_options(q)

    print("开始自检…")
    errs = check()
    if errs:
        print("自检失败：")
        for e in errs:
            print("  -", e)
        sys.exit(1)
    if len(Q) != 100:
        print("自检失败：题目总数为 %d，期望 100" % len(Q))
        sys.exit(1)

    # 自检通过后再去掉候选池：产出文件里只保留最终的四个选项
    for q in Q:
        del q["pool"]

    elements = [{"id": i, "name": n, "category": c, "level": l, "summary": s,
                 "image": IMG + i + (".jpg" if i.startswith("photo_") else ".svg")}
                for i, n, c, l, s in E]

    os.makedirs(DATA, exist_ok=True)
