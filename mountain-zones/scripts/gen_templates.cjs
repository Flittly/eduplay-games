/**
 * 整型 hash → [0,1)（值噪声的格点取值）。
 *
 * ⚠️ **必须全程用 `Math.imul` 整数运算**，不能用 `Math.sin`：
 * `Math.sin` 的最后一位由引擎决定，跨机器/跨版本可能差一 ⇒ 同一份源码
 * 在两台机器上生成出两座不同的山，而"模板应当是确定的"是硬要求
 * （`template.test.cjs` 靠 `B64_SHA` 逐字节钉住落盘数据）。
 * 这与上面 `hash01()` 选 `Math.imul` 是同一条理由。
 */
function hashV(i, j, seed) {
  let x = Math.imul(i + 0x9e37, 0x85ebca6b) ^ Math.imul(j + 0x79b9, 0xc2b2ae35) ^ Math.imul(seed + 0x1f83, 0x27d4eb2f);
  x = Math.imul(x ^ (x >>> 15), 0x2545f491);
  x ^= x >>> 13;
  x = Math.imul(x ^ (x >>> 16), 0x9e3779b1);
  x ^= x >>> 15;
  return (x >>> 0) / 4294967296;
}

/**
 * 二维值噪声：格点 `hashV` + **smoothstep 双三次插值** ⇒ C1 连续。
 *
 * 位置在格点阵的**连续坐标**上取，所以输出对输入是光滑的。
 * 返回 [−1, 1]。
 *
 * ⚠️ 插值权重必须与 `smoothstep` 同族。用线性插值会得到 C0 场，
 * 而 C0 的格点脊线在等高线上会出现**折线尖角** —— 那正是"人工感"的一种。
 */
function vnoise(x, y, seed) {
  const xi = Math.floor(x);
  const yi = Math.floor(y);
  const xf = x - xi;
  const yf = y - yi;
  const u = xf * xf * (3 - 2 * xf);
  const v = yf * yf * (3 - 2 * yf);
  const a = hashV(xi, yi, seed);
  const b = hashV(xi + 1, yi, seed);
  const c = hashV(xi, yi + 1, seed);
  const d = hashV(xi + 1, yi + 1, seed);
  const top = a + (b - a) * u;
  const bot = c + (d - c) * u;
  return (top + (bot - top) * v) * 2 - 1;
}

/**
 * fBm（分形布朗运动）：`oct` 个倍频叠加，频率 ×`lac`、振幅 ×`gain`。
 *
 * 单个倍频只有一个特征尺寸，看起来像"一团雾"；真实地面在**每个尺度上**
 * 都同时粗糙（幂律谱），所以必须叠倍频。这是网上程序化地形配方的基础件
 * （THREE.Terrain 等），但那些配方**只用它做底**，还要叠 ridged 折叠与水力侵蚀；
 * 模板地形不能照抄 —— 纯噪声没有"峰"与"鞍"的概念，满屏都是小起伏，
 * 机器判据会检出几十个部位，教学上不可用（见 `buildMountain` 的说明）。
 *
 * @param inv  空间频率（1/米）：越大细节越碎
 * @returns    [−1, 1] 附近（归一化后严格落在 [−1,1]）
 */
function fbm(x, y, oct, inv, lac, gain, seed) {
  let f = 1;
  let a = 1;
  let sum = 0;
  let norm = 0;
  for (let o = 0; o < oct; o++) {
    sum += a * vnoise(x * inv * f, y * inv * f, seed + o * 97);
    norm += a;
    f *= lac;
    a *= gain;
  }
  return sum / norm;
}

