def validate(items, dims):
    ids = [x["id"] for x in items]
    assert len(ids) == len(set(ids)), "id 重复"
    for x in items:
        for f in ("id", "name", "en", "category", "type", "country", "region",
                  "lat", "lon", "photo", "summary", "intro", "traits", "cause",
                  "personality", "profile"):
            assert f in x, "%s 缺字段 %s" % (x.get("id"), f)
        assert x["category"] in ("domestic", "international"), x["id"]
        assert -90 <= x["lat"] <= 90 and -180 <= x["lon"] <= 180, x["id"]
        assert x["photo"] == "./assets/landforms/%s.jpg" % x["id"], x["id"]
        assert len(x["traits"]) >= 3, x["id"]
        assert set(x["profile"].keys()) == set(dims), x["id"]
        for v in x["profile"].values():
            assert isinstance(v, int) and 0 <= v <= 100, x["id"]
    sigs = {}
    for x in items:
        sig = tuple(x["profile"][d] for d in dims)
        assert sig not in sigs, "profile 完全相同的两条: %s / %s" % (sigs.get(sig), x["id"])
        sigs[sig] = x["id"]


def main():
    check_only = "--check" in sys.argv
    data = json.load(io.open(DATA, encoding="utf-8"))
    dims = [d["key"] for d in data["dimensions"]]
    assert dims == DIMS, dims

    old = data["landforms"]
    by_id = {x["id"]: x for x in old}

    added_cn = added_intl = updated = 0
    for x in NEW_CN + NEW_INTL:
        if x["id"] in by_id:
            base = by_id[x["id"]]
            base.update(x)
            updated += 1
        else:
            by_id[x["id"]] = x
            if x["category"] == "domestic":
                added_cn += 1
            else:
                added_intl += 1

    merged = [x for x in by_id.values() if x["category"] == "domestic"]
    merged += [x for x in by_id.values() if x["category"] == "international"]

    validate(merged, dims)

    print("新增 国内 %d 条 / 国外 %d 条，覆盖更新 %d 条" % (added_cn, added_intl, updated))
    print("合并后总数 %d（国内 %d + 国外 %d）"
          % (len(merged),
             sum(1 for x in merged if x["category"] == "domestic"),
             sum(1 for x in merged if x["category"] == "international")))

    if check_only:
        print("--check：仅校验，未写盘")
        return

    data["landforms"] = merged
    io.open(DATA, "w", encoding="utf-8", newline="\n").write(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print("已写回", DATA)


if __name__ == "__main__":
    main()
